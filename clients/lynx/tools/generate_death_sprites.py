#!/usr/bin/env python3
"""Encode existing smoke art ahead of time, including Suzy's zero guards."""
import argparse
from pathlib import Path
import re

root = Path(__file__).resolve().parents[1]
rows = re.findall(r'"([.WYOLGD]{12})"', (root / 'src/death_art.h').read_text())
assert len(rows) == 36
pens = {'.': 0, 'W': 15, 'Y': 9, 'O': 8, 'L': 4, 'G': 5, 'D': 6}
lines = ['/* Generated by tools/generate_death_sprites.py from death_art.h.',
         '   Every literal row retains its hardware-required zero guard. */',
         'static const uint8_t death_sprites[4][73] = {']
for frame in range(4):
    lines.append('    {')
    for row in rows[frame*9:frame*9+9]:
        packet = [8] + [pens[row[i]]*16+pens[row[i+1]] for i in range(0,12,2)] + [0]
        lines.append('        '+', '.join(f'0x{p:02x}' for p in packet)+',')
    lines.append('        0\n    },')
lines.append('};\n')
expected = '\n'.join(lines)
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
target = root / 'src/death_sprites.h'
if args.check:
    if target.read_text() != expected:
        raise SystemExit('death_sprites.h is stale; run tools/generate_death_sprites.py')
else:
    target.write_text(expected)
