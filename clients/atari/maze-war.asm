; store the name for slot pid and ask the VBI to repaint the HUD labels.
NET_NAME_APPLY
	LDA	NET_NAME_PKT+2	;pid
	CMP	#4
	BCS	NNA_X
	ASL			;pid*8 -> table offset
	ASL
	ASL
	TAY
	LDX	#0
NNA_CP
