; --- NET snapshot apply (type 0x40, 20 bytes) ---
NET_SNAP_APPLY
	LDA	NET_SNAP_BUF+2	;flags must indicate valid snapshot
	AND	#$01
	BNE	NSNAP_OK
	RTS
NSNAP_OK
	JSR	NET_SNAP_VALIDATE
	BCC	NSNAP_VOK
	RTS
NSNAP_VOK
	; ignore stale/duplicate/out-of-order snapshots to prevent snap-back.
	LDA	NET_RX_DBG
	BNE	NSNAP_CHKSEQ
	LDA	#1
	STA	NET_RX_DBG
	LDA	NET_SNAP_BUF+1
	STA	NET_RX_SEQ
	JMP	NSNAP_ACC
NSNAP_CHKSEQ
	; accept forward modulo-256 seq deltas in range 1..127, drop stale/dup.
	LDA	NET_SNAP_BUF+1
	SEC
	SBC	NET_RX_SEQ
	BEQ	NSNAP_DROP
	CMP	#$80
	BCS	NSNAP_DROP
	LDA	NET_SNAP_BUF+1
	STA	NET_RX_SEQ
	JMP	NSNAP_ACC
NSNAP_DROP
	JMP	NSNAP_EXIT
NSNAP_ACC
	LDA	#0	;authoritative state arrived: reset the stall watchdog
	STA	NET_WAIT_LO
	STA	NET_WAIT_HI
	; latest-wins staged snapshot handoff:
	; odd seq = mainline is writing staging
	; even seq = latest full snapshot ready for VBI commit
	LDA	NET_STAGE_SEQ
	CLC
	ADC	#1
	STA	NET_STAGE_SEQ
	; flags bit3..6 = authoritative zombie mask for slots 0..3
	LDA	NET_SNAP_BUF+2
	LSR
	LSR
	LSR
	AND	#$0F
	STA	NET_ROLE_NEW
	EOR	NET_ROLE_MASK	;slots whose role changed this snapshot
	BEQ	NSNAP_RMSK
	STA	NET_ROLE_CHG
	LDA	NET_ROLE_NEW
	STA	NET_ROLE_MASK
	LDA	#1
	STA	NET_SCORE_PEND
	JSR	NET_ROLE_RESET
NSNAP_RMSK
	LDA	NET_BOOT_HIDE
	BEQ	NSNAP_POS0
	LDA	NET_BRICK_DONE
	BNE	NSNAP_BOK
	JMP	NSNAP_EXIT
NSNAP_BOK
	LDA	#0
	STA	NET_BOOT_HIDE
	STA	NET_DEAD_MASK
	STA	NET_ERASE_MASK
	LDA	#1
	LDX	#3
NSNAP_FPP
	STA	NET_STAGE_PENDING,X
	DEX
	BPL	NSNAP_FPP
NSNAP_POS0
	; stage authoritative positions for VBI-owned live commit.
	; mainline RX never touches NET_PX_* / NET_P_PENDING directly.
	LDA	#0
	STA	NET_STAGE_ACK_VALID
	LDA	NET_SNAP_BUF+2
	AND	#$80
	BEQ	NSNAP_NOACK
	LDA	#1
	STA	NET_STAGE_ACK_VALID
	LDA	NET_SNAP_BUF+19
	STA	NET_STAGE_ACK_SEQ
NSNAP_NOACK
	LDA	NET_SNAP_BUF+2
	LSR
	AND	#$03
