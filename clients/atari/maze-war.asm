	CMP	LOCX,X
	BNE	RC_BUSY
	LDA	RNDY,X
	CMP	LOCY,X
	BNE	RC_BUSY
	LDA	#0		;hand control back to the player
	STA	NET_RCHASE
	STA	NET_P_PENDING,X
	STA	NET_DESYNC_CNT,X
