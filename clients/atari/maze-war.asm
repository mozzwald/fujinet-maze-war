	BEQ	NET_RX_51CLR
	JSR	NET_BRICK_DELTA_APPLY
NET_RX_51CLR
	LDA	#0
	STA	NET_RX_STATE
	STA	NET_SNAP_IDX
	RTS
NET_RX_52DONE
